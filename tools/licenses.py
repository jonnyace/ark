#!/usr/bin/env python3
"""Write docs/LICENSES.md: the licence of every third-party component that ships in the apps.
Sources: `cargo metadata` (native + desktop dependency graphs, normal deps only) and `pnpm licenses list --prod`
(web app runtime packages). Library content and model licences are listed per pack, not here."""
import json, subprocess, os, collections
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(root)

def cargo(manifest):
    m = json.loads(subprocess.check_output(["cargo", "metadata", "--format-version", "1", "--locked", "--manifest-path", manifest], text=True))
    pk = {p["id"]: p for p in m["packages"]}
    nodes = {n["id"]: n for n in m["resolve"]["nodes"]}
    seen, todo = set(), [m["resolve"]["root"]] if m["resolve"]["root"] else list(m["workspace_members"])
    while todo:
        i = todo.pop()
        if i in seen: continue
        seen.add(i)
        for d in nodes[i]["deps"]:
            if any(k["kind"] in (None, "normal") for k in d["dep_kinds"]): todo.append(d["pkg"])
    return {(pk[i]["name"], pk[i]["version"]): (pk[i].get("license") or "SEE " + str(pk[i].get("license_file")), pk[i].get("repository") or "")
            for i in seen if pk[i]["source"]}

rust = {}
for mf in ["Cargo.toml", "apps/desktop/src-tauri/Cargo.toml"]:
    rust.update(cargo(mf))
web = json.loads(subprocess.check_output("pnpm licenses list --prod --json", shell=True, cwd="apps/web", text=True))
out = ["# Third-party licences", "",
       "Generated by `tools/licenses.py` from the locked dependency graphs. Code licences only: library content and",
       "model weights keep their own licences, recorded in each pack (`pack.json` → `license`, `LICENSES/`), and the",
       "components fetched or bundled outside these graphs are in NOTICE.md (llama.cpp, map fonts and sprites, models).",
       "The Rust list is a superset: `cargo metadata` includes crates used only on other platforms (Windows, macOS).",
       "MPL-2.0 crates (file-level copyleft, via Tauri) are used unmodified; their source is on crates.io.", "",
       "## Summary", ""]
cnt = collections.Counter(v[0] for v in rust.values())
for lic, items in web.items(): cnt[lic] += len(items)
out += [f"| Licence | Packages |", "|---|---|"] + [f"| {k} | {v} |" for k, v in sorted(cnt.items(), key=lambda x: -x[1])]
out += ["", "## Rust crates (desktop app, CLI, engine)", "", "| Crate | Version | Licence |", "|---|---|---|"]
out += [f"| {n} | {v} | {l} |" for (n, v), (l, _) in sorted(rust.items())]
out += ["", "## JavaScript packages shipped in the web app", "", "| Package | Version | Licence |", "|---|---|---|"]
for lic, items in sorted(web.items()):
    for it in items:
        out.append(f"| {it['name']} | {', '.join(it.get('versions', [it.get('version', '')]))} | {lic} |")
open("docs/LICENSES.md", "w").write("\n".join(out) + "\n")
gpl = [k for k in cnt if "GPL" in k and "LGPL" not in k]
print(f"docs/LICENSES.md: {len(rust)} crates, {sum(len(v) for v in web.values())} npm packages; licences: {dict(cnt)}")
if gpl: print("NOTE copyleft licences present:", gpl)
